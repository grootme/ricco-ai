"""
Health State Machine for RICCO AI

Implements the Health State Machine meta-pattern for comprehensive
health monitoring with state transitions, alerting, and auto-recovery.

Part of the Resilience-Aware Architecture DNA.

States:
- HEALTHY: All systems operational
- DEGRADED: Some components experiencing issues but functional
- UNHEALTHY: Critical issues affecting functionality
- RECOVERING: System is recovering from an unhealthy state
"""

import asyncio
import time
from typing import Dict, Any, Optional, List, Callable
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
import logging

logger = logging.getLogger(__name__)


# ============================================================================
# Enums and Data Classes
# ============================================================================

class HealthState(str, Enum):
    """Health states for components and system"""
    HEALTHY = "healthy"
    DEGRADED = "degraded"
    UNHEALTHY = "unhealthy"
    RECOVERING = "recovering"
    UNKNOWN = "unknown"


class AlertSeverity(str, Enum):
    """Alert severity levels"""
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"
    RESOLVED = "resolved"


@dataclass
class HealthCheckResult:
    """Result of a health check"""
    name: str
    status: HealthState
    message: str
    timestamp: float = field(default_factory=time.time)
    details: Dict[str, Any] = field(default_factory=dict)
    latency_ms: Optional[float] = None


@dataclass
class HealthAlert:
    """Alert generated by health state transitions"""
    id: str
    component: str
    severity: AlertSeverity
    message: str
    previous_state: HealthState
    current_state: HealthState
    created_at: float = field(default_factory=time.time)
    resolved_at: Optional[float] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class TransitionRule:
    """Rule for health state transitions"""
    from_state: HealthState
    to_state: HealthState
    condition: Optional[Callable[[Dict], bool]] = None
    action: Optional[Callable[[Dict], None]] = None
    alert_severity: Optional[AlertSeverity] = None
    cooldown_seconds: float = 30.0


# ============================================================================
# Component Health Monitor
# ============================================================================

class ComponentHealthMonitor:
    """
    Health monitor for a single component
    
    Implements:
    - Health check execution
    - State transitions with guards
    - Alert generation
    - Recovery detection
    """
    
    def __init__(
        self,
        name: str,
        check_func: Callable[[], Any],
        check_interval: float = 30.0,
        failure_threshold: int = 3,
        recovery_threshold: int = 2,
        timeout: float = 5.0,
    ):
        self.name = name
        self.check_func = check_func
        self.check_interval = check_interval
        self.failure_threshold = failure_threshold
        self.recovery_threshold = recovery_threshold
        self.timeout = timeout
        
        self._state = HealthState.UNKNOWN
        self._consecutive_failures = 0
        self._consecutive_successes = 0
        self._last_check: Optional[HealthCheckResult] = None
        self._last_state_change: float = 0
        self._check_task: Optional[asyncio.Task] = None
        self._running = False
        
        # Callbacks
        self._on_state_change: List[Callable[[HealthState, HealthState], None]] = []
        self._on_alert: List[Callable[[HealthAlert], None]] = []
    
    @property
    def state(self) -> HealthState:
        return self._state
    
    @property
    def last_check(self) -> Optional[HealthCheckResult]:
        return self._last_check
    
    def on_state_change(self, callback: Callable[[HealthState, HealthState], None]):
        """Register callback for state changes"""
        self._on_state_change.append(callback)
    
    def on_alert(self, callback: Callable[[HealthAlert], None]):
        """Register callback for alerts"""
        self._on_alert.append(callback)
    
    async def check(self) -> HealthCheckResult:
        """Execute health check and return result"""
        start_time = time.time()
        
        try:
            # Execute check with timeout
            if asyncio.iscoroutinefunction(self.check_func):
                result = await asyncio.wait_for(
                    self.check_func(),
                    timeout=self.timeout
                )
            else:
                result = await asyncio.get_event_loop().run_in_executor(
                    None, self.check_func
                )
            
            latency = (time.time() - start_time) * 1000
            
            # Process result
            if isinstance(result, HealthCheckResult):
                check_result = result
                check_result.latency_ms = latency
            elif isinstance(result, dict):
                check_result = HealthCheckResult(
                    name=self.name,
                    status=HealthState(result.get("status", "healthy")),
                    message=result.get("message", "OK"),
                    details=result.get("details", {}),
                    latency_ms=latency,
                )
            elif isinstance(result, bool):
                check_result = HealthCheckResult(
                    name=self.name,
                    status=HealthState.HEALTHY if result else HealthState.UNHEALTHY,
                    message="OK" if result else "Check failed",
                    latency_ms=latency,
                )
            else:
                check_result = HealthCheckResult(
                    name=self.name,
                    status=HealthState.HEALTHY,
                    message="OK",
                    latency_ms=latency,
                )
            
            # Track successes
            self._consecutive_successes += 1
            self._consecutive_failures = 0
            
        except asyncio.TimeoutError:
            check_result = HealthCheckResult(
                name=self.name,
                status=HealthState.UNHEALTHY,
                message=f"Health check timed out after {self.timeout}s",
                latency_ms=self.timeout * 1000,
            )
            self._consecutive_failures += 1
            self._consecutive_successes = 0
            
        except Exception as e:
            check_result = HealthCheckResult(
                name=self.name,
                status=HealthState.UNHEALTHY,
                message=f"Health check error: {str(e)}",
            )
            self._consecutive_failures += 1
            self._consecutive_successes = 0
        
        self._last_check = check_result
        self._update_state()
        
        return check_result
    
    def _update_state(self):
        """Update state based on check results"""
        previous_state = self._state
        
        # State transition logic
        if self._consecutive_failures >= self.failure_threshold:
            new_state = HealthState.UNHEALTHY
        elif self._consecutive_failures > 0:
            new_state = HealthState.DEGRADED
        elif self._consecutive_successes >= self.recovery_threshold:
            new_state = HealthState.HEALTHY
        else:
            new_state = self._state
        
        # Apply transition
        if new_state != self._state:
            self._state = new_state
            self._last_state_change = time.time()
            
            # Notify callbacks
            for callback in self._on_state_change:
                try:
                    callback(previous_state, new_state)
                except Exception as e:
                    logger.error(f"State change callback error: {e}")
            
            # Generate alert
            self._generate_alert(previous_state, new_state)
    
    def _generate_alert(self, previous: HealthState, current: HealthState):
        """Generate alert for state transition"""
        severity = self._determine_severity(previous, current)
        
        alert = HealthAlert(
            id=f"{self.name}-{int(time.time())}",
            component=self.name,
            severity=severity,
            message=f"Health state changed from {previous.value} to {current.value}",
            previous_state=previous,
            current_state=current,
            metadata={
                "consecutive_failures": self._consecutive_failures,
                "consecutive_successes": self._consecutive_successes,
                "last_check_message": self._last_check.message if self._last_check else None,
            },
        )
        
        for callback in self._on_alert:
            try:
                callback(alert)
            except Exception as e:
                logger.error(f"Alert callback error: {e}")
    
    def _determine_severity(
        self,
        previous: HealthState,
        current: HealthState
    ) -> AlertSeverity:
        """Determine alert severity based on transition"""
        if current == HealthState.HEALTHY:
            return AlertSeverity.RESOLVED
        elif current == HealthState.UNHEALTHY:
            return AlertSeverity.CRITICAL
        elif current == HealthState.DEGRADED:
            return AlertSeverity.WARNING
        else:
            return AlertSeverity.INFO
    
    async def start(self):
        """Start periodic health checks"""
        if self._running:
            return
        
        self._running = True
        self._check_task = asyncio.create_task(self._check_loop())
        logger.info(f"Started health monitor for {self.name}")
    
    async def stop(self):
        """Stop health checks"""
        self._running = False
        if self._check_task:
            self._check_task.cancel()
            try:
                await self._check_task
            except asyncio.CancelledError:
                pass
        logger.info(f"Stopped health monitor for {self.name}")
    
    async def _check_loop(self):
        """Periodic health check loop"""
        while self._running:
            try:
                await self.check()
            except Exception as e:
                logger.error(f"Health check error for {self.name}: {e}")
            
            await asyncio.sleep(self.check_interval)


