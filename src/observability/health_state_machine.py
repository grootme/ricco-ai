def create_database_check(db_client, query: str = "SELECT 1") -> Callable:
    """Create a database health check"""
    async def check() -> Dict[str, Any]:
        try:
            if asyncio.iscoroutinefunction(db_client.execute):
                await db_client.execute(query)
            else:
                db_client.execute(query)
            return {"status": "healthy", "message": "Database connection OK"}
        except Exception as e:
            return {"status": "unhealthy", "message": str(e)}
    return check


def create_redis_check(redis_client) -> Callable:
    """Create a Redis health check"""
    async def check() -> Dict[str, Any]:
        try:
            if asyncio.iscoroutinefunction(redis_client.ping):
                await redis_client.ping()
            else:
                redis_client.ping()
            return {"status": "healthy", "message": "Redis connection OK"}
        except Exception as e:
            return {"status": "unhealthy", "message": str(e)}
    return check


def create_http_check(url: str, expected_status: int = 200) -> Callable:
    """Create an HTTP endpoint health check"""
    import httpx
    
    async def check() -> Dict[str, Any]:
        try:
            async with httpx.AsyncClient() as client:
                response = await client.get(url, timeout=5.0)
            
            if response.status_code == expected_status:
                return {"status": "healthy", "message": f"HTTP {url} OK"}
            else:
                return {
                    "status": "degraded",
                    "message": f"HTTP {url} returned {response.status_code}",
                }
        except Exception as e:
            return {"status": "unhealthy", "message": str(e)}
    return check


def create_vector_store_check(store_client, collection: str) -> Callable:
    """Create a vector store health check"""
    async def check() -> Dict[str, Any]:
        try:
            if hasattr(store_client, 'health_check'):
                await store_client.health_check()
            return {
                "status": "healthy",
                "message": f"Vector store {collection} OK",
                "details": {"collection": collection}
            }
        except Exception as e:
            return {"status": "unhealthy", "message": str(e)}
    return check
