_system_health: Optional[SystemHealthStateMachine] = None


def get_system_health() -> SystemHealthStateMachine:
    """Get or create the system health state machine"""
    global _system_health
    if _system_health is None:
        _system_health = SystemHealthStateMachine()
    return _system_health


