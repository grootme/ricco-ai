class SystemHealthStateMachine:
    """
    System-level health state machine
    
    Aggregates component health into system health state with:
    - State transitions with cooldown
    - Alert generation
    - Recovery detection
    - Metrics export
    """
    
    # Transition rules
    TRANSITIONS: Dict[HealthState, List[TransitionRule]] = {
        HealthState.HEALTHY: [
            TransitionRule(HealthState.HEALTHY, HealthState.DEGRADED,
                          alert_severity=AlertSeverity.WARNING),
            TransitionRule(HealthState.HEALTHY, HealthState.UNHEALTHY,
                          alert_severity=AlertSeverity.CRITICAL),
        ],
        HealthState.DEGRADED: [
            TransitionRule(HealthState.DEGRADED, HealthState.HEALTHY,
                          alert_severity=AlertSeverity.RESOLVED),
            TransitionRule(HealthState.DEGRADED, HealthState.UNHEALTHY,
                          alert_severity=AlertSeverity.CRITICAL),
            TransitionRule(HealthState.DEGRADED, HealthState.RECOVERING,
                          alert_severity=AlertSeverity.INFO),
        ],
        HealthState.UNHEALTHY: [
            TransitionRule(HealthState.UNHEALTHY, HealthState.RECOVERING,
                          alert_severity=AlertSeverity.INFO),
            TransitionRule(HealthState.UNHEALTHY, HealthState.DEGRADED,
                          alert_severity=AlertSeverity.WARNING),
        ],
        HealthState.RECOVERING: [
            TransitionRule(HealthState.RECOVERING, HealthState.HEALTHY,
                          alert_severity=AlertSeverity.RESOLVED),
            TransitionRule(HealthState.RECOVERING, HealthState.UNHEALTHY,
                          alert_severity=AlertSeverity.CRITICAL),
        ],
    }
    
    def __init__(self):
        self._state = HealthState.UNKNOWN
        self._components: Dict[str, ComponentHealthMonitor] = {}
        self._alerts: List[HealthAlert] = []
        self._last_transition: float = 0
        self._transition_history: List[Dict[str, Any]] = []
        
        # Callbacks
        self._on_system_state_change: List[Callable[[HealthState, HealthState, Dict], None]] = []
        self._on_system_alert: List[Callable[[HealthAlert], None]] = []
    
    @property
    def state(self) -> HealthState:
        return self._state
    
    def register_component(self, monitor: ComponentHealthMonitor):
        """Register a component health monitor"""
        self._components[monitor.name] = monitor
        
        # Wire up callbacks
        monitor.on_state_change(
            lambda p, c: self._on_component_state_change(monitor.name, p, c)
        )
        monitor.on_alert(self._on_component_alert)
    
    def on_system_state_change(
        self,
        callback: Callable[[HealthState, HealthState, Dict], None]
    ):
        """Register callback for system state changes"""
        self._on_system_state_change.append(callback)
    
    def on_system_alert(self, callback: Callable[[HealthAlert], None]):
        """Register callback for system alerts"""
        self._on_system_alert.append(callback)
    
    def _on_component_state_change(
        self,
        component: str,
        previous: HealthState,
        current: HealthState
    ):
        """Handle component state change"""
        logger.info(f"Component {component} state changed: {previous.value} -> {current.value}")
        self._update_system_state()
    
    def _on_component_alert(self, alert: HealthAlert):
        """Handle component alert"""
        self._alerts.append(alert)
        
        # Keep only recent alerts
        cutoff = time.time() - 3600  # 1 hour
        self._alerts = [a for a in self._alerts if a.created_at > cutoff]
    
    def _update_system_state(self):
        """Update system state based on component states"""
        if not self._components:
            return
        
        # Count states
        state_counts = {s: 0 for s in HealthState}
        for monitor in self._components.values():
            state_counts[monitor.state] += 1
        
        total = len(self._components)
        
        # Determine system state
        if state_counts[HealthState.UNHEALTHY] > 0:
            new_state = HealthState.UNHEALTHY
        elif state_counts[HealthState.DEGRADED] > 0:
            new_state = HealthState.DEGRADED
        elif state_counts[HealthState.RECOVERING] > 0:
            new_state = HealthState.RECOVERING
        elif state_counts[HealthState.HEALTHY] == total:
            new_state = HealthState.HEALTHY
        else:
            new_state = HealthState.UNKNOWN
        
        # Apply transition if valid
        if new_state != self._state:
            self._apply_transition(new_state, state_counts)
    
    def _apply_transition(
        self,
        new_state: HealthState,
        component_states: Dict[HealthState, int]
    ):
        """Apply state transition with validation"""
        previous = self._state
        
        # Find applicable rule
        rules = self.TRANSITIONS.get(previous, [])
        rule = next(
            (r for r in rules if r.to_state == new_state),
            None
        )
        
        if rule:
            # Check cooldown
            elapsed = time.time() - self._last_transition
            if elapsed < rule.cooldown_seconds:
                logger.debug(f"Transition on cooldown for {rule.cooldown_seconds - elapsed:.1f}s")
                return
            
            # Apply transition
            self._state = new_state
            self._last_transition = time.time()
            
            # Execute action
            if rule.action:
                try:
                    rule.action(component_states)
                except Exception as e:
                    logger.error(f"Transition action error: {e}")
            
            # Record history
            self._transition_history.append({
                "from": previous.value,
                "to": new_state.value,
                "timestamp": time.time(),
                "component_states": {s.value: c for s, c in component_states.items()},
            })
            
            # Keep only recent history
            cutoff = time.time() - 86400  # 24 hours
            self._transition_history = [
                h for h in self._transition_history
                if h["timestamp"] > cutoff
            ]
            
            # Generate alert
            if rule.alert_severity:
                alert = HealthAlert(
                    id=f"system-{int(time.time())}",
                    component="system",
                    severity=rule.alert_severity,
                    message=f"System health changed from {previous.value} to {new_state.value}",
                    previous_state=previous,
                    current_state=new_state,
                )
                self._alerts.append(alert)
                
                for callback in self._on_system_alert:
                    try:
                        callback(alert)
                    except Exception as e:
                        logger.error(f"System alert callback error: {e}")
            
            # Notify callbacks
            for callback in self._on_system_state_change:
                try:
                    callback(previous, new_state, component_states)
                except Exception as e:
                    logger.error(f"System state change callback error: {e}")
            
            logger.info(f"System health: {previous.value} -> {new_state.value}")
    
    async def check_all(self) -> Dict[str, HealthCheckResult]:
        """Check all components"""
        results = {}
        tasks = {
            name: monitor.check()
            for name, monitor in self._components.items()
        }
        
        check_results = await asyncio.gather(*tasks.values(), return_exceptions=True)
        
        for (name, monitor), result in zip(self._components.items(), check_results):
            if isinstance(result, Exception):
                results[name] = HealthCheckResult(
                    name=name,
                    status=HealthState.UNHEALTHY,
                    message=f"Check failed: {result}",
                )
            else:
                results[name] = result
        
        self._update_system_state()
        return results
    
    async def start_all(self):
        """Start all component monitors"""
        for monitor in self._components.values():
            await monitor.start()
    
    async def stop_all(self):
        """Stop all component monitors"""
        for monitor in self._components.values():
            await monitor.stop()
    
    def get_status(self) -> Dict[str, Any]:
        """Get current health status"""
        return {
            "system_state": self._state.value,
            "components": {
                name: {
                    "state": monitor.state.value,
                    "last_check": monitor.last_check.message if monitor.last_check else None,
                    "last_check_time": monitor.last_check.timestamp if monitor.last_check else None,
                }
                for name, monitor in self._components.items()
            },
            "active_alerts": [
                {
                    "id": a.id,
                    "component": a.component,
                    "severity": a.severity.value,
                    "message": a.message,
                    "created_at": datetime.fromtimestamp(a.created_at).isoformat(),
                }
                for a in self._alerts
                if not a.resolved_at
            ],
            "transition_count": len(self._transition_history),
        }


